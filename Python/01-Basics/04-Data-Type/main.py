# Data Type in Python
# Integer (int) - Whole numbers, positive or negative, without decimals
# Float (float) - Numbers with decimal points
# String (str) - Sequence of characters enclosed in quotes
# Boolean (bool) - Represents True or False values

# Data Type Examples
age = 25
year = 2002
balance = -50000
zero = 0

print("Integer Examples:")
print("Age:", age)
print("Year:", year)
print("Balance:", balance)
print("Zero:", zero)

# Float Examples
height = 5.9
weight = 70.5

print("\nFloat Examples:")
print("Height:", height)
print("Weight:", weight)

# String Examples
first = "Petrus"
last = 'Handika'

full_name = first + " " + last

print("\nString Examples:")
print("First Name:", first)
print("Last Name:", last)
print("Full Name:", full_name)

# Boolean Examples
student = True
programmer = False

print("\nBoolean Examples:")
print("Is a student:", student)
print("Is a programmer:", programmer)